#!/usr/bin/env node
// Stripe webhook registration helper — Rubberfit Stripe rollout PR 3.
//
// Creates (or updates) the webhook endpoint in Stripe and prints the
// signing secret you paste into .env.local / Vercel as
// STRIPE_WEBHOOK_SECRET. Idempotent: if a webhook with the same URL
// already exists, we reuse it. Live mode is gated behind --confirm-live.
//
// Usage:
//   node scripts/stripe-webhook-register.mjs https://app.rubberfit.com/api/stripe/webhook
//   node scripts/stripe-webhook-register.mjs --dry-run http://localhost:3000/api/stripe/webhook
//   node scripts/stripe-webhook-register.mjs --confirm-live https://app.rubberfit.com/api/stripe/webhook
//
// Reads STRIPE_SECRET_KEY from .env.local automatically.

import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import path from "node:path"
import Stripe from "stripe"

const REPO_ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)))

const ENABLED_EVENTS = [
  "checkout.session.completed",
  "customer.subscription.created",
  "customer.subscription.updated",
  "customer.subscription.deleted",
  "customer.subscription.trial_will_end",
  "invoice.paid",
  "invoice.payment_failed",
]

function loadEnvLocal() {
  try {
    const content = readFileSync(path.join(REPO_ROOT, ".env.local"), "utf8")
    for (const rawLine of content.split("\n")) {
      const line = rawLine.trim()
      if (!line || line.startsWith("#")) continue
      const eq = line.indexOf("=")
      if (eq === -1) continue
      const key = line.slice(0, eq).trim()
      let value = line.slice(eq + 1).trim()
      if (
        (value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))
      ) {
        value = value.slice(1, -1)
      }
      if (!process.env[key]) process.env[key] = value
    }
  } catch {
    // ignore
  }
}

function detectMode(apiKey) {
  if (apiKey.startsWith("sk_test_")) return "test"
  if (apiKey.startsWith("sk_live_")) return "live"
  throw new Error("STRIPE_SECRET_KEY has unexpected prefix")
}

async function findExistingEndpoint(stripe, url) {
  let starting_after
  do {
    const page = await stripe.webhookEndpoints.list({ limit: 100, starting_after })
    for (const ep of page.data) {
      if (ep.url === url) return ep
    }
    starting_after = page.has_more ? page.data[page.data.length - 1].id : undefined
  } while (starting_after)
  return null
}

async function main() {
  loadEnvLocal()

  const args = process.argv.slice(2)
  const dryRun = args.includes("--dry-run")
  const confirmLive = args.includes("--confirm-live")
  const url = args.find((a) => a.startsWith("http"))

  if (!url) {
    throw new Error(
      "Pass the webhook URL as an argument, e.g.:\n  node scripts/stripe-webhook-register.mjs https://app.rubberfit.com/api/stripe/webhook"
    )
  }

  const apiKey = process.env.STRIPE_SECRET_KEY
  if (!apiKey) throw new Error("STRIPE_SECRET_KEY not set")
  const mode = detectMode(apiKey)

  if (mode === "live" && !confirmLive && !dryRun) {
    throw new Error("Live mode requires --confirm-live to register a live webhook")
  }

  console.log(`Stripe webhook register — mode: ${mode}${dryRun ? " (dry-run)" : ""}`)
  console.log(`URL: ${url}`)
  console.log(`Events: ${ENABLED_EVENTS.length} subscribed`)
  console.log("")

  const stripe = new Stripe(apiKey, { apiVersion: "2026-04-22.dahlia", typescript: false })

  const existing = await findExistingEndpoint(stripe, url)
  if (existing) {
    if (dryRun) {
      console.log(`[dry-run] would update endpoint ${existing.id} (events list)`)
      return
    }
    const updated = await stripe.webhookEndpoints.update(existing.id, {
      enabled_events: ENABLED_EVENTS,
      description: "Rubberfit billing — generated by stripe-webhook-register",
      metadata: { app: "rubberfit", product: "rubberfit" },
    })
    console.log(`Endpoint already exists — updated ${updated.id}`)
    console.log("")
    console.log(
      "Note: Stripe only returns the signing secret on initial creation. If you need it, rotate via the Dashboard or delete + recreate."
    )
    console.log(`Stripe Dashboard: https://dashboard.stripe.com/${mode === "live" ? "" : "test/"}webhooks/${updated.id}`)
    return
  }

  if (dryRun) {
    console.log(`[dry-run] would create endpoint at ${url}`)
    return
  }

  const created = await stripe.webhookEndpoints.create({
    url,
    enabled_events: ENABLED_EVENTS,
    description: "Rubberfit billing — generated by stripe-webhook-register",
    metadata: { app: "rubberfit", product: "rubberfit" },
    api_version: "2026-04-22.dahlia",
  })

  console.log(`Created endpoint ${created.id}`)
  console.log("")
  console.log(`Stripe Dashboard: https://dashboard.stripe.com/${mode === "live" ? "" : "test/"}webhooks/${created.id}`)
  console.log("")
  console.log("─────────────────────────────────────────────────────────────")
  console.log("Paste this signing secret into .env.local / Vercel env as STRIPE_WEBHOOK_SECRET:")
  console.log("")
  console.log(`  STRIPE_WEBHOOK_SECRET=${created.secret}`)
  console.log("")
  console.log("─────────────────────────────────────────────────────────────")
  console.log("This secret is only shown ONCE. Rotate via the Dashboard if lost.")
}

main().catch((err) => {
  console.error("")
  console.error("stripe-webhook-register failed:", err.message)
  if (process.env.STRIPE_DEBUG) console.error(err)
  process.exitCode = 1
})
