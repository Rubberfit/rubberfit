/**
 * Step 7c-1 service-level tests for the idempotent receive flow.
 *
 * `PurchaseOrderService.recordReceiptsByItemId` is the single point
 * where the idempotency contract is enforced: INSERT into
 * `po_item_receipts` FIRST (ON CONFLICT DO NOTHING), then apply the
 * entity, then stamp `applied_at`. These tests use a fake repo so
 * the sequencing and conflict semantics are observable without
 * standing up Supabase.
 */
import "reflect-metadata"
import { beforeEach, describe, expect, it } from "vitest"

import { PurchaseOrder } from "@/src/entities/purchase-order"
import { PurchaseOrderItem } from "@/src/entities/purchase-order-item"
import { Currency } from "@/src/entities/value-objects/currency"
import {
  MaterialTypeId,
  ProfileId,
  PurchaseOrderId,
  SupplierId,
  TenantId,
} from "@/src/entities/value-objects/id"
import { Money } from "@/src/entities/value-objects/money"
import type {
  IPurchaseOrdersRepository,
  InsertReceiptInput,
  InsertReceiptResult,
} from "@/src/application/repositories/purchase-orders.repository.interface"
import { PurchaseOrderService } from "@/src/infrastructure/services/purchaseOrderService"

const PO_UUID = "10000000-1000-4000-8000-bbbbbbbbbbb1"
const TENANT_UUID = "20000000-2000-4000-8000-bbbbbbbbbbb2"
const SUPPLIER_UUID = "30000000-3000-4000-8000-bbbbbbbbbbb3"
const MT_UUID = "40000000-4000-4000-8000-bbbbbbbbbbb4"
const ITEM1_UUID = "50000000-5000-4000-8000-bbbbbbbbbbb5"
const ITEM2_UUID = "50000000-5000-4000-8000-bbbbbbbbbbb6"
const ACTOR_UUID = "60000000-6000-4000-8000-bbbbbbbbbbb7"
const KEY_A = "90000000-9000-4000-8000-bbbbbbbbbbb8"

const USD = Currency.fromPersistence("USD")

function makePoItem(lineNumber: number, qtySqm = 25): PurchaseOrderItem {
  return PurchaseOrderItem.create({
    lineNumber,
    materialTypeId: MaterialTypeId.fromPersistence(MT_UUID),
    quantitySqm: qtySqm,
    widthMm: 1500,
    thicknessMm: 2.5,
    unitCost: Money.fromCents(1000, USD),
  })
}

function makePoOrdered(items: PurchaseOrderItem[]): PurchaseOrder {
  const subtotal = items.reduce((sum, i) => sum.add(i.lineTotal), Money.fromCents(0, USD))
  const taxAmount = Money.fromCents(0, USD)
  const shippingCost = Money.fromCents(0, USD)
  const totalAmount = subtotal.add(taxAmount).add(shippingCost)
  return PurchaseOrder.reconstitute({
    id: PurchaseOrderId.fromPersistence(PO_UUID),
    tenantId: TenantId.fromPersistence(TENANT_UUID),
    supplierId: SupplierId.fromPersistence(SUPPLIER_UUID),
    shippingAddress: null,
    billingAddress: null,
    reorderRuleId: null,
    jobId: null,
    poNumber: "PO-2026-0099",
    status: "ordered",
    orderDate: new Date("2026-04-15T00:00:00.000Z"),
    requestedDeliveryDate: new Date("2026-05-01T00:00:00.000Z"),
    actualDeliveryDate: null,
    subtotal,
    taxAmount,
    shippingCost,
    totalAmount,
    paymentTerms: null,
    notes: null,
    autoGenerated: false,
    approvedBy: ProfileId.fromPersistence(ACTOR_UUID),
    approvedAt: new Date("2026-04-10T00:00:00.000Z"),
    items,
    createdAt: new Date("2026-04-01T00:00:00.000Z"),
    createdBy: ProfileId.fromPersistence(ACTOR_UUID),
    updatedAt: new Date("2026-05-01T00:00:00.000Z"),
    updatedBy: ProfileId.fromPersistence(ACTOR_UUID),
    deletedAt: null,
  })
}

interface ReceiptRow extends InsertReceiptInput {
  receiptId: string
  appliedAt: Date | null
  rollCreatedAt: Date | null
}

/**
 * In-memory repo fake. Emulates the (item_id, idempotency_key) UNIQUE
 * constraint via a Map keyed on the composite tuple.
 */
class FakeRepo implements IPurchaseOrdersRepository {
  readonly receipts = new Map<string, ReceiptRow>()
  readonly callLog: string[] = []
  shouldFailUpdate = false
  private nextReceiptIdCounter = 1

  constructor(private poRef: PurchaseOrder) {}

  async findById(): Promise<PurchaseOrder> {
    return this.poRef
  }
  async findActive(): Promise<PurchaseOrder[]> {
    return [this.poRef]
  }
  async findByStatuses(): Promise<PurchaseOrder[]> {
    return [this.poRef]
  }
  async insert(po: PurchaseOrder): Promise<PurchaseOrder> {
    this.poRef = po
    return po
  }
  async itemIdToLineNumberMap(): Promise<Map<string, number>> {
    const map = new Map<string, number>()
    for (const item of this.poRef.items) {
      // Hardcode: lineNumber 1 → ITEM1_UUID, lineNumber 2 → ITEM2_UUID.
      const id = item.lineNumber === 1 ? ITEM1_UUID : ITEM2_UUID
      map.set(id, item.lineNumber)
    }
    return map
  }
  async update(po: PurchaseOrder): Promise<PurchaseOrder> {
    this.callLog.push("update")
    if (this.shouldFailUpdate) {
      throw new Error("simulated repo.update failure")
    }
    this.poRef = po
    return po
  }

  async findReceiptById(_receiptId: string): Promise<never> {
    throw new Error("FakeRepo.findReceiptById not used by these tests")
  }
  async findPendingApplyReceipts() { return [] }
  async findPendingRollCreationReceipts() { return [] }

  async insertReceiptIdempotent(input: InsertReceiptInput): Promise<InsertReceiptResult> {
    this.callLog.push(`insertReceiptIdempotent:${input.purchaseOrderItemId}`)
    const key = `${input.purchaseOrderItemId}::${input.idempotencyKey}`
    const existing = this.receipts.get(key)
    if (existing) {
      return { receiptId: existing.receiptId, wasInserted: false }
    }
    const receiptId = `r-${this.nextReceiptIdCounter++}`
    const row: ReceiptRow = {
      ...input,
      receiptId,
      appliedAt: null,
      rollCreatedAt: null,
    }
    this.receipts.set(key, row)
    return { receiptId, wasInserted: true }
  }

  async markReceiptApplied(receiptId: string): Promise<void> {
    this.callLog.push(`markReceiptApplied:${receiptId}`)
    for (const row of this.receipts.values()) {
      if (row.receiptId === receiptId) {
        row.appliedAt = new Date()
        return
      }
    }
  }

  async markReceiptRollCreated(receiptId: string): Promise<void> {
    this.callLog.push(`markReceiptRollCreated:${receiptId}`)
    for (const row of this.receipts.values()) {
      if (row.receiptId === receiptId) {
        row.rollCreatedAt = new Date()
        return
      }
    }
  }
}

describe("PurchaseOrderService.recordReceiptsByItemId — idempotency (7c-1)", () => {
  let repo: FakeRepo
  let service: PurchaseOrderService

  beforeEach(() => {
    const items = [makePoItem(1, 100), makePoItem(2, 100)]
    repo = new FakeRepo(makePoOrdered(items))
    service = new PurchaseOrderService(repo)
  })

  it("first call: receipt INSERT → entity apply → repo.update → applied_at stamp (in that order)", async () => {
    const result = await service.recordReceiptsByItemId(
      PO_UUID,
      [
        {
          itemId: ITEM1_UUID,
          quantityReceivedSqm: 50,
          idempotencyKey: KEY_A,
          rollRequested: false,
        },
      ],
      ProfileId.fromPersistence(ACTOR_UUID)
    )

    expect(result.alreadyAppliedItemIds).toEqual([])
    expect(result.receiptIdByItemId.get(ITEM1_UUID)).toBe("r-1")

    // Strict ordering: INSERT comes first, then update, then stamp.
    expect(repo.callLog).toEqual([
      `insertReceiptIdempotent:${ITEM1_UUID}`,
      "update",
      "markReceiptApplied:r-1",
    ])

    // The receipt row carries the applied_at stamp.
    const row = Array.from(repo.receipts.values())[0]!
    expect(row.appliedAt).not.toBeNull()
  })

  it("retry with same key: skips entity apply, marks item as alreadyApplied", async () => {
    const input = [
      {
        itemId: ITEM1_UUID,
        quantityReceivedSqm: 50,
        idempotencyKey: KEY_A,
        rollRequested: false,
      },
    ]
    const actor = ProfileId.fromPersistence(ACTOR_UUID)
    await service.recordReceiptsByItemId(PO_UUID, input, actor)
    repo.callLog.length = 0 // reset

    const result = await service.recordReceiptsByItemId(PO_UUID, input, actor)

    expect(result.alreadyAppliedItemIds).toEqual([ITEM1_UUID])
    // Stable receipt id returned even on conflict (same row).
    expect(result.receiptIdByItemId.get(ITEM1_UUID)).toBe("r-1")

    // The second call ONLY hits insertReceiptIdempotent (which conflicts);
    // no entity apply, no repo.update, no stamp.
    expect(repo.callLog).toEqual([`insertReceiptIdempotent:${ITEM1_UUID}`, "update"])
    // ↑ Note: repo.update STILL runs because the service persists the
    //   entity after the apply-loop regardless of whether the loop did
    //   any work. The aggregate is in the same state, so update is a
    //   no-op-shaped write. We DO NOT stamp applied_at again.
    expect(repo.callLog).not.toContain("markReceiptApplied:r-1")
  })

  it("mixed: same key on item A (already applied), fresh on item B", async () => {
    const actor = ProfileId.fromPersistence(ACTOR_UUID)
    // Prime: apply item A.
    await service.recordReceiptsByItemId(
      PO_UUID,
      [
        {
          itemId: ITEM1_UUID,
          quantityReceivedSqm: 50,
          idempotencyKey: KEY_A,
          rollRequested: false,
        },
      ],
      actor
    )

    // Second call: same key, A + B. A conflicts; B inserts fresh.
    const result = await service.recordReceiptsByItemId(
      PO_UUID,
      [
        {
          itemId: ITEM1_UUID,
          quantityReceivedSqm: 50,
          idempotencyKey: KEY_A,
          rollRequested: false,
        },
        {
          itemId: ITEM2_UUID,
          quantityReceivedSqm: 30,
          idempotencyKey: KEY_A,
          rollRequested: false,
        },
      ],
      actor
    )

    expect(result.alreadyAppliedItemIds).toEqual([ITEM1_UUID])
    expect(result.receiptIdByItemId.get(ITEM1_UUID)).toBe("r-1")
    expect(result.receiptIdByItemId.get(ITEM2_UUID)).toBe("r-2")

    // r-2 (the fresh one) gets applied_at; r-1 keeps its original stamp,
    // not re-stamped.
    const r2 = Array.from(repo.receipts.values()).find((r) => r.receiptId === "r-2")!
    expect(r2.appliedAt).not.toBeNull()
  })

  it("repo.update failure: receipt row exists with applied_at IS NULL (under-applied window)", async () => {
    repo.shouldFailUpdate = true

    await expect(
      service.recordReceiptsByItemId(
        PO_UUID,
        [
          {
            itemId: ITEM1_UUID,
            quantityReceivedSqm: 50,
            idempotencyKey: KEY_A,
            rollRequested: false,
          },
        ],
        ProfileId.fromPersistence(ACTOR_UUID)
      )
    ).rejects.toThrow(/repo\.update/)

    // The receipt row landed but applied_at is NULL — this is the row
    // that po_receipts_pending_apply would surface for admin reconcile.
    const row = Array.from(repo.receipts.values())[0]!
    expect(row.appliedAt).toBeNull()
    expect(repo.callLog).toContain(`insertReceiptIdempotent:${ITEM1_UUID}`)
    expect(repo.callLog).toContain("update")
    expect(repo.callLog).not.toContain("markReceiptApplied:r-1")
  })

  it("persists typed rollIntent onto the receipt row", async () => {
    await service.recordReceiptsByItemId(
      PO_UUID,
      [
        {
          itemId: ITEM1_UUID,
          quantityReceivedSqm: 50,
          idempotencyKey: KEY_A,
          rollRequested: true,
          rollIntent: {
            widthMm: 1524,
            lengthMm: 50000,
            thicknessMm: 3.175,
            color: "black",
            location: "Bay A",
            costPerSqmCents: 5400,
            notes: "neoprene",
          },
        },
      ],
      ProfileId.fromPersistence(ACTOR_UUID)
    )

    const row = Array.from(repo.receipts.values())[0]!
    expect(row.rollRequested).toBe(true)
    expect(row.rollIntent).toMatchObject({
      widthMm: 1524,
      color: "black",
      costPerSqmCents: 5400,
    })
  })
})
