const PO_UUID = "10000000-1000-4000-8000-dddddddddd01"
const TENANT_UUID = "20000000-2000-4000-8000-dddddddddd02"
const SUPPLIER_UUID = "30000000-3000-4000-8000-dddddddddd03"
const MT_UUID = "40000000-4000-4000-8000-dddddddddd04"
const ITEM1_UUID = "50000000-5000-4000-8000-dddddddddd05"
const ACTOR_UUID = "60000000-6000-4000-8000-dddddddddd06"
const RECEIPT_UUID = "a0000000-a000-4000-8000-dddddddddd07"
const ROLL_UUID = "b0000000-b000-4000-8000-dddddddddd08"
const KEY_A = "90000000-9000-4000-8000-dddddddddd09"

const USD = Currency.fromPersistence("USD")

function makePoItem(lineNumber: number, qtySqm = 100): PurchaseOrderItem {
  return PurchaseOrderItem.create({
    lineNumber,
    materialTypeId: MaterialTypeId.fromPersistence(MT_UUID),
    quantitySqm: qtySqm,
    widthMm: 1500,
    thicknessMm: 2.5,
    unitCost: Money.fromCents(1000, USD),
  })
}

function makePo(items: PurchaseOrderItem[]): PurchaseOrder {
  const subtotal = items.reduce((sum, i) => sum.add(i.lineTotal), Money.fromCents(0, USD))
  return PurchaseOrder.reconstitute({
    id: PurchaseOrderId.fromPersistence(PO_UUID),
    tenantId: TenantId.fromPersistence(TENANT_UUID),
    supplierId: SupplierId.fromPersistence(SUPPLIER_UUID),
    shippingAddress: null,
    billingAddress: null,
    reorderRuleId: null,
    jobId: null,
    poNumber: "PO-2026-0099",
    status: "partial_received",
    orderDate: new Date("2026-04-15T00:00:00.000Z"),
    requestedDeliveryDate: new Date("2026-05-01T00:00:00.000Z"),
    actualDeliveryDate: null,
    subtotal,
    taxAmount: Money.fromCents(0, USD),
    shippingCost: Money.fromCents(0, USD),
    totalAmount: subtotal,
    paymentTerms: null,
    notes: null,
    autoGenerated: false,
    approvedBy: ProfileId.fromPersistence(ACTOR_UUID),
    approvedAt: new Date("2026-04-10T00:00:00.000Z"),
    items,
    createdAt: new Date("2026-04-01T00:00:00.000Z"),
    createdBy: ProfileId.fromPersistence(ACTOR_UUID),
    updatedAt: new Date("2026-05-01T00:00:00.000Z"),
    updatedBy: ProfileId.fromPersistence(ACTOR_UUID),
    deletedAt: null,
  })
}

function makeReceipt(overrides: Partial<PoItemReceiptWithContext> = {}): PoItemReceiptWithContext {
  return {
    receiptId: RECEIPT_UUID,
    tenantId: TENANT_UUID,
    purchaseOrderItemId: ITEM1_UUID,
    idempotencyKey: KEY_A,
    quantityReceivedSqm: 50,
    receivedDate: new Date("2026-05-10T00:00:00.000Z"),
    receiptCreatedAt: new Date("2026-05-10T08:00:00.000Z"),
    receiptCreatedBy: ACTOR_UUID,
    purchaseOrderId: PO_UUID,
    lineNumber: 1,
    materialTypeId: MT_UUID,
    poNumber: "PO-2026-0099",
    supplierId: SUPPLIER_UUID,
    purchaseOrderStatus: "partial_received",
    rollWidthMm: 1500,
    rollLengthMm: 12000,
    rollThicknessMm: 2.5,
    rollColor: "black",
    rollLocation: "Receiving",
    rollCostPerSqmCents: 1000,
    rollNotes: null,
    rollRequested: true,
    appliedAt: new Date("2026-05-10T08:30:00.000Z"),
    rollCreatedAt: null,
    ...overrides,
  }
}

function makeRoll(): Roll {
  return Roll.create({
    id: RollId.fromPersistence(ROLL_UUID),
    tenantId: TenantId.fromPersistence(TENANT_UUID),
    materialTypeId: MaterialTypeId.fromPersistence(MT_UUID),
    supplierId: SupplierId.fromPersistence(SUPPLIER_UUID),
    sourceType: "received",
    purchaseOrderItemId: PurchaseOrderItemId.fromPersistence(ITEM1_UUID),
    widthMm: 1500,
    lengthMm: 12000,
    thicknessMm: 2.5,
    cost: Money.fromCents(1000, USD),
    createdBy: ProfileId.fromPersistence(ACTOR_UUID),
  })
}

