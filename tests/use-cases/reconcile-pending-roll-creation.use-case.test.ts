describe("ReconcilePendingRollCreationUseCase", () => {
  let poService: IPurchaseOrderService
  let rollService: IRollService
  let useCase: ReconcilePendingRollCreationUseCase
  const actor = {
    id: ACTOR_UUID,
    email: "admin@example.com",
    roles: ["admin"],
    isSuperAdmin: false,
    activeTenantId: TENANT_UUID,
  }

  beforeEach(() => {
    container.clearInstances()
    poService = makeFakePoService()
    rollService = makeFakeRollService()
    container.registerInstance(TOKENS.IPurchaseOrderService, poService)
    container.registerInstance(TOKENS.IRollService, rollService)
    useCase = container.resolve(ReconcilePendingRollCreationUseCase)
  })

  it("happy path: replays createRoll, stamps roll_created_at, returns created outcome", async () => {
    vi.mocked(poService.findReceiptById).mockResolvedValue(makeReceipt())
    vi.mocked(poService.getById).mockResolvedValue(makePo([makePoItem(1, 100)]))
    vi.mocked(rollService.findByPurchaseOrderItemId).mockResolvedValue(null)
    const newRoll = makeRoll()
    vi.mocked(rollService.createRoll).mockResolvedValue(newRoll)

    const result = await useCase.execute({ receiptId: RECEIPT_UUID, actor })

    expect(result.kind).toBe("created")
    expect(result.roll).toBe(newRoll)
    expect(rollService.createRoll).toHaveBeenCalledTimes(1)
    expect(poService.markReceiptRollCreated).toHaveBeenCalledWith(RECEIPT_UUID)
    // Sanity-check that createRoll got props derived from the receipt's
    // typed snapshot — width/length/thickness flow through from the
    // receipt fields, not the PO-item fallbacks.
    const createCall = vi.mocked(rollService.createRoll).mock.calls[0]![0]
    expect(createCall.widthMm).toBe(1500)
    expect(createCall.lengthMm).toBe(12000)
    expect(createCall.purchaseOrderItemId?.value).toBe(ITEM1_UUID)
  })

  it("already-exists: matching roll found before createRoll → stamps and returns existing", async () => {
    vi.mocked(poService.findReceiptById).mockResolvedValue(makeReceipt())
    const existing = makeRoll()
    vi.mocked(rollService.findByPurchaseOrderItemId).mockResolvedValue(existing)

    const result = await useCase.execute({ receiptId: RECEIPT_UUID, actor })

    expect(result.kind).toBe("already-exists")
    expect(result.roll).toBe(existing)
    expect(rollService.createRoll).not.toHaveBeenCalled()
    expect(poService.markReceiptRollCreated).toHaveBeenCalledWith(RECEIPT_UUID)
  })

  it("already-stamped: rollCreatedAt populated → loads existing roll, no createRoll, no stamp", async () => {
    vi.mocked(poService.findReceiptById).mockResolvedValue(
      makeReceipt({ rollCreatedAt: new Date("2026-05-10T09:00:00.000Z") })
    )
    const existing = makeRoll()
    vi.mocked(rollService.findByPurchaseOrderItemId).mockResolvedValue(existing)

    const result = await useCase.execute({ receiptId: RECEIPT_UUID, actor })

    expect(result.kind).toBe("already-stamped")
    expect(result.roll).toBe(existing)
    expect(rollService.createRoll).not.toHaveBeenCalled()
    expect(poService.markReceiptRollCreated).not.toHaveBeenCalled()
  })

  it("throws when receipt.rollRequested = false (no roll to reconcile)", async () => {
    vi.mocked(poService.findReceiptById).mockResolvedValue(makeReceipt({ rollRequested: false }))

    await expect(useCase.execute({ receiptId: RECEIPT_UUID, actor })).rejects.toBeInstanceOf(
      InvalidEntityError
    )
    expect(rollService.createRoll).not.toHaveBeenCalled()
    expect(poService.markReceiptRollCreated).not.toHaveBeenCalled()
  })

  it("throws when appliedAt is null (apply must be reconciled first)", async () => {
    vi.mocked(poService.findReceiptById).mockResolvedValue(makeReceipt({ appliedAt: null }))

    await expect(useCase.execute({ receiptId: RECEIPT_UUID, actor })).rejects.toBeInstanceOf(
      InvalidEntityError
    )
    expect(rollService.createRoll).not.toHaveBeenCalled()
    expect(poService.markReceiptRollCreated).not.toHaveBeenCalled()
  })

  it("throws when PO has no item matching receipt.lineNumber", async () => {
    vi.mocked(poService.findReceiptById).mockResolvedValue(makeReceipt({ lineNumber: 99 }))
    vi.mocked(poService.getById).mockResolvedValue(makePo([makePoItem(1, 100)]))
    vi.mocked(rollService.findByPurchaseOrderItemId).mockResolvedValue(null)

    await expect(useCase.execute({ receiptId: RECEIPT_UUID, actor })).rejects.toBeInstanceOf(
      InvalidEntityError
    )
    expect(rollService.createRoll).not.toHaveBeenCalled()
  })

  it("swallows stamp failure after successful createRoll (view excludes via NOT EXISTS)", async () => {
    vi.mocked(poService.findReceiptById).mockResolvedValue(makeReceipt())
    vi.mocked(poService.getById).mockResolvedValue(makePo([makePoItem(1, 100)]))
    vi.mocked(rollService.findByPurchaseOrderItemId).mockResolvedValue(null)
    const newRoll = makeRoll()
    vi.mocked(rollService.createRoll).mockResolvedValue(newRoll)
    vi.mocked(poService.markReceiptRollCreated).mockRejectedValue(new Error("stamp failed"))
    const consoleErrorSpy = vi.spyOn(console, "error").mockImplementation(() => {})

    const result = await useCase.execute({ receiptId: RECEIPT_UUID, actor })

    expect(result.kind).toBe("created")
    expect(result.roll).toBe(newRoll)
    expect(consoleErrorSpy).toHaveBeenCalled()
    consoleErrorSpy.mockRestore()
  })
})
