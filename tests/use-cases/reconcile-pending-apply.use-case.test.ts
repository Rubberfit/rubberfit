describe("ReconcilePendingApplyUseCase", () => {
  let poService: IPurchaseOrderService
  let useCase: ReconcilePendingApplyUseCase
  const actor = {
    id: ACTOR_UUID,
    email: "admin@example.com",
    roles: ["admin"],
    isSuperAdmin: false,
    activeTenantId: TENANT_UUID,
  }

  beforeEach(() => {
    container.clearInstances()
    poService = makeFakePoService()
    container.registerInstance(TOKENS.IPurchaseOrderService, poService)
    useCase = container.resolve(ReconcilePendingApplyUseCase)
  })

  it("happy path: re-applies receipt on entity, stamps applied_at", async () => {
    const item = makePoItem(1, 100)
    vi.mocked(poService.findReceiptById).mockResolvedValue(makeReceipt())
    const updatedPo = makePoInStatus("partial_received", [item])
    vi.mocked(poService.recordReceipts).mockResolvedValue(updatedPo)

    const result = await useCase.execute({ receiptId: RECEIPT_UUID, actor })

    expect(result.alreadyApplied).toBe(false)
    expect(result.purchaseOrder).toBe(updatedPo)
    expect(poService.recordReceipts).toHaveBeenCalledTimes(1)
    expect(poService.markReceiptApplied).toHaveBeenCalledWith(RECEIPT_UUID)
    const recordCall = vi.mocked(poService.recordReceipts).mock.calls[0]!
    expect(recordCall[0]).toBe(PO_UUID)
    expect(recordCall[1]).toEqual([
      {
        lineNumber: 1,
        quantityReceivedSqm: 50,
        receivedDate: new Date("2026-05-10T00:00:00.000Z"),
      },
    ])
  })

  it("idempotent: appliedAt already populated → no recordReceipts call, returns current PO", async () => {
    vi.mocked(poService.findReceiptById).mockResolvedValue(
      makeReceipt({ appliedAt: new Date("2026-05-10T09:00:00.000Z") })
    )
    const currentPo = makePoInStatus("received", [makePoItem(1, 100)])
    vi.mocked(poService.getById).mockResolvedValue(currentPo)

    const result = await useCase.execute({ receiptId: RECEIPT_UUID, actor })

    expect(result.alreadyApplied).toBe(true)
    expect(result.purchaseOrder).toBe(currentPo)
    expect(poService.recordReceipts).not.toHaveBeenCalled()
    expect(poService.markReceiptApplied).not.toHaveBeenCalled()
  })

  it("propagates entity error when PO is in wrong state (e.g., cancelled)", async () => {
    vi.mocked(poService.findReceiptById).mockResolvedValue(makeReceipt())
    vi.mocked(poService.recordReceipts).mockRejectedValue(
      new Error("can only record receipts on POs in 'ordered' or 'partial_received'")
    )

    await expect(useCase.execute({ receiptId: RECEIPT_UUID, actor })).rejects.toThrow(
      /can only record receipts/
    )
    expect(poService.markReceiptApplied).not.toHaveBeenCalled()
  })
})
