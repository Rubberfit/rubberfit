const PO_UUID = "10000000-1000-4000-8000-cccccccccc01"
const TENANT_UUID = "20000000-2000-4000-8000-cccccccccc02"
const SUPPLIER_UUID = "30000000-3000-4000-8000-cccccccccc03"
const MT_UUID = "40000000-4000-4000-8000-cccccccccc04"
const ITEM1_UUID = "50000000-5000-4000-8000-cccccccccc05"
const ACTOR_UUID = "60000000-6000-4000-8000-cccccccccc06"
const RECEIPT_UUID = "a0000000-a000-4000-8000-cccccccccc07"
const KEY_A = "90000000-9000-4000-8000-cccccccccc08"

const USD = Currency.fromPersistence("USD")

function makePoItem(lineNumber: number, qtySqm = 100): PurchaseOrderItem {
  return PurchaseOrderItem.create({
    lineNumber,
    materialTypeId: MaterialTypeId.fromPersistence(MT_UUID),
    quantitySqm: qtySqm,
    widthMm: 1500,
    thicknessMm: 2.5,
    unitCost: Money.fromCents(1000, USD),
  })
}

function makePoInStatus(
  status: "ordered" | "partial_received" | "received" | "cancelled",
  items: PurchaseOrderItem[]
): PurchaseOrder {
  const subtotal = items.reduce((sum, i) => sum.add(i.lineTotal), Money.fromCents(0, USD))
  return PurchaseOrder.reconstitute({
    id: PurchaseOrderId.fromPersistence(PO_UUID),
    tenantId: TenantId.fromPersistence(TENANT_UUID),
    supplierId: SupplierId.fromPersistence(SUPPLIER_UUID),
    shippingAddress: null,
    billingAddress: null,
    reorderRuleId: null,
    jobId: null,
    poNumber: "PO-2026-0099",
    status,
    orderDate: new Date("2026-04-15T00:00:00.000Z"),
    requestedDeliveryDate: new Date("2026-05-01T00:00:00.000Z"),
    actualDeliveryDate: status === "received" ? new Date("2026-05-12T00:00:00.000Z") : null,
    subtotal,
    taxAmount: Money.fromCents(0, USD),
    shippingCost: Money.fromCents(0, USD),
    totalAmount: subtotal,
    paymentTerms: null,
    notes: null,
    autoGenerated: false,
    approvedBy: ProfileId.fromPersistence(ACTOR_UUID),
    approvedAt: new Date("2026-04-10T00:00:00.000Z"),
    items,
    createdAt: new Date("2026-04-01T00:00:00.000Z"),
    createdBy: ProfileId.fromPersistence(ACTOR_UUID),
    updatedAt: new Date("2026-05-01T00:00:00.000Z"),
    updatedBy: ProfileId.fromPersistence(ACTOR_UUID),
    deletedAt: null,
  })
}

