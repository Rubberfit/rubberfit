export function AppSidebar({ ...props }: React.ComponentProps<typeof Sidebar>) {
  const { user } = useAuth();
  const { can, isLoading } = useRole();
  const { sidebarVariant, sidebarCollapsible, isSynced } = usePreferencesStore(
    useShallow((s) => ({
      sidebarVariant: s.sidebarVariant,
      sidebarCollapsible: s.sidebarCollapsible,
      isSynced: s.isSynced,
    })),
  );

  const variant = isSynced ? sidebarVariant : props.variant;
  const collapsible = isSynced ? sidebarCollapsible : props.collapsible;
  // Filter nav items based on the current user's role
  const visibleItems = sidebarItems
  .map(group => ({
    ...group,
    items: group.items
      .filter(item => !item.requiredPermission || can(item.requiredPermission))
      .map(item => ({
        ...item,
        // Filter sub-items the same way
        subItems: item.subItems?.filter(sub =>
          !sub.requiredPermission || can(sub.requiredPermission)
        ),
      })),
  }))
  .filter(group => group.items.length > 0);
  return (
    <Sidebar {...props} variant={variant} collapsible={collapsible}>
      <SidebarHeader>
        <SidebarMenu>
          <SidebarMenuItem>
            <SidebarMenuButton asChild>
              <Link prefetch={false} href={homeHref}>
                <Command />
                <span className="font-semibold text-base">{APP_CONFIG.name}</span>
              </Link>
            </SidebarMenuButton>
          </SidebarMenuItem>
        </SidebarMenu>
      </SidebarHeader>
      <SidebarContent>
        {isLoading ? null : <NavMain items={visibleItems} />}
        {/* <NavDocuments items={data.documents} /> */}
        {/* <NavSecondary items={data.navSecondary} className="mt-auto" /> */}
      </SidebarContent>
      <SidebarFooter>
        {user && (
          <NavUser
            user={{
              name: user.name || user.email,
              email: user.email,
              avatar: user.avatar || ""
            }}
          />
        )}
      </SidebarFooter>
    </Sidebar>
  );
}
