"use client";

import { useState, useEffect } from "react";
import { Bell, Package, AlertTriangle, Clock, CheckCircle, Eye, X } from "lucide-react";

import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Trash2 } from "lucide-react";
import { toast } from "sonner";
import { notificationCrudService } from "@/services/notificationCrudService";
import { materialTypeService } from "@/services/materialTypeService";
import { rollService } from "@/services/rollService";
import { cutService } from "@/services/cutService";
import { globalEvents, EVENTS } from "@/lib/events";
import { useRouter } from "next/navigation";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";

interface Notification {
  id: string;
  type: string;
  title: string;
  description: string;
  material_type?: string;
  current_value?: number;
  threshold_value?: number;
  is_read: boolean;
  created_at: string;
  updated_at?: string;
}

interface Activity {
  id: string;
  type: 'cut' | 'roll_added' | 'roll_depleted';
  description: string;
  timestamp: string;
  job_reference?: string;
  material_type?: string;
  waste_percentage?: number;
}

export default function NotificationsPage() {
  const router = useRouter();
  const [notifications, setNotifications] = useState<Notification[]>([]);
  const [activities, setActivities] = useState<Activity[]>([]);
  const [loading, setLoading] = useState(true);
  const [selectedNotification, setSelectedNotification] = useState<Notification | null>(null);
  const [detailModalOpen, setDetailModalOpen] = useState(false);
  const [unreadCount, setUnreadCount] = useState(0);

  useEffect(() => {
    fetchNotifications();
    fetchRecentActivities();
    // Don't auto-generate notifications - they should be generated by database triggers or manual refresh
  }, []);

  const generateLowStockNotifications = async () => {
    try {
      // First check if notifications table exists
      const tableExists = await notificationCrudService.exists();

      // If table doesn't exist, skip generation
      if (!tableExists) {
        console.log('Notifications table not yet created, skipping generation');
        return;
      }

      // Check and generate low stock notifications
      const materialTypes = await materialTypeService.getAll();
      const rolls = await rollService.getActiveRolls();

      // Calculate stock levels
      const stockLevels = new Map<string, number>();
      if (rolls) {
        rolls.forEach(roll => {
          const sqft = (roll.remaining_length * roll.width) / 144;
          const current = stockLevels.get(roll.material_type) || 0;
          stockLevels.set(roll.material_type, current + sqft);
        });
      }

      // First, get all existing low stock notifications to prevent duplicates
      const existingNotifications = await notificationCrudService.getByType('low_stock');

      const existingByMaterial = new Map<string, string>();
      if (existingNotifications) {
        existingNotifications.forEach(n => {
          existingByMaterial.set(n.material_type, n.id);
        });
      }

      // Batch process notifications
      const notificationsToInsert: any[] = [];
      const notificationsToUpdate: any[] = [];
      const materialsWithLowStock = new Set<string>();

      if (materialTypes) {
        for (const materialType of materialTypes) {
          const currentStock = stockLevels.get(materialType.name) || 0;
          const threshold = materialType.min_stock_alert || 0;

          if (currentStock < threshold && threshold > 0) {
            materialsWithLowStock.add(materialType.name);

            const existingId = existingByMaterial.get(materialType.name);

            if (existingId) {
              // Only update existing notification if stock got worse or if it's currently unread
              // Don't resurrect cleared/deleted notifications
              const existingNotif = existingNotifications?.find(n => n.id === existingId);
              if (existingNotif) {
                notificationsToUpdate.push({
                  id: existingId,
                  current_value: currentStock,
                  description: `Current stock (${currentStock.toFixed(1)} sqft) is below threshold (${threshold} sqft)`,
                  // Don't change read status - keep it as is
                  updated_at: new Date().toISOString()
                });
              }
            } else {
              // Create new notification (only if it doesn't exist)
              notificationsToInsert.push({
                type: 'low_stock',
                title: `${materialType.name} Low Stock Alert`,
                description: `Current stock (${currentStock.toFixed(1)} sqft) is below threshold (${threshold} sqft)`,
                material_type: materialType.name,
                current_value: currentStock,
                threshold_value: threshold,
                is_read: false
              });
            }
          }
        }

        // Update existing notifications (only update values, not read status)
        for (const update of notificationsToUpdate) {
          await notificationCrudService.update(update.id, {
            current_value: update.current_value,
            description: update.description,
            // Don't update is_read - leave it as is
            updated_at: update.updated_at
          });
        }

        // Insert only truly new notifications
        if (notificationsToInsert.length > 0) {
          console.log(`Creating ${notificationsToInsert.length} new notifications`);
          try {
            await notificationCrudService.bulkCreate(notificationsToInsert);
          } catch (insertError) {
            console.error('Error inserting notifications:', insertError);
          }
        } else {
          console.log('No new notifications to create');
        }

        // Remove notifications for materials that are no longer low on stock
        const allLowStockNotifs = await notificationCrudService.getByType('low_stock');

        if (allLowStockNotifs) {
          const toDelete = allLowStockNotifs
            .filter(n => !materialsWithLowStock.has(n.material_type))
            .map(n => n.id);

          if (toDelete.length > 0) {
            await notificationCrudService.deleteByIds(toDelete);
          }
        }
      }
    } catch (error) {
      console.error('Error generating low stock notifications:', error);
    }
  };

  const fetchNotifications = async () => {
    try {
      setLoading(true);

      // First, clean up any duplicates by keeping only the latest notification per material type
      // Get all notifications grouped by material_type (already ordered by created_at desc)
      const allNotifs = await notificationCrudService.getAll();

      // Find and remove duplicates
      const seen = new Set<string>();
      const toDelete: string[] = [];
      const uniqueNotifications: Notification[] = [];

      if (allNotifs) {
        for (const notif of allNotifs) {
          const key = `${notif.type}_${notif.material_type || 'none'}`;
          if (notif.type === 'low_stock' && seen.has(key)) {
            // This is a duplicate, mark for deletion
            toDelete.push(notif.id);
          } else {
            seen.add(key);
            uniqueNotifications.push(notif);
          }
        }

        // Delete duplicates if found
        if (toDelete.length > 0) {
          console.log(`Cleaning up ${toDelete.length} duplicate notifications`);
          await notificationCrudService.deleteByIds(toDelete);
        }
      }

      // Use the deduplicated list
      const data = uniqueNotifications;

      setNotifications(data || []);
      setUnreadCount(data?.filter(n => !n.is_read).length || 0);
    } catch (error: any) {
      console.error('Error fetching notifications:', error?.message || error);
      // Don't show error toast for table not existing
      if (!error?.message?.includes('relation') && !error?.message?.includes('does not exist')) {
        toast.error('Failed to load notifications');
      }
    } finally {
      setLoading(false);
    }
  };

  const fetchRecentActivities = async () => {
    try {
      // Fetch recent cuts with roll info
      let cuts: any[] | null = null;
      try {
        cuts = await cutService.getRecentCutsWithRolls(10);
      } catch (cutsError: any) {
        if (cutsError?.code !== 'PGRST116') {
          console.error('Error fetching cuts:', cutsError);
        }
      }

      // Fetch recent roll changes
      let rolls: any[] | null = null;
      try {
        rolls = await rollService.getRecentlyUpdatedRolls(10);
      } catch (rollsError: any) {
        if (rollsError?.code !== 'PGRST116') {
          console.error('Error fetching rolls:', rollsError);
        }
      }

      // Combine and format activities
      const formattedActivities: Activity[] = [];

      if (cuts) {
        cuts.forEach(cut => {
          // cutService.getRecentCutsWithRolls aliases the join as 'roll'
          const rollInfo = cut.roll as any;
          formattedActivities.push({
            id: cut.id,
            type: 'cut',
            description: `Cut ${cut.cut_width}" × ${cut.cut_length}" × ${cut.quantity} from ${rollInfo?.material_type || 'Unknown'}`,
            timestamp: cut.created_at,
            job_reference: cut.job_reference,
            material_type: rollInfo?.material_type,
            waste_percentage: cut.waste_percentage
          });
        });
      }

      if (rolls) {
        rolls.forEach(roll => {
          if (roll.status === 'depleted') {
            formattedActivities.push({
              id: roll.id,
              type: 'roll_depleted',
              description: `${roll.material_type} roll ${roll.width}" × ${roll.length}" depleted`,
              timestamp: roll.updated_at,
              material_type: roll.material_type
            });
          } else if (new Date(roll.created_at).getTime() > Date.now() - 7 * 24 * 60 * 60 * 1000) {
            formattedActivities.push({
              id: roll.id,
              type: 'roll_added',
              description: `New ${roll.material_type} roll ${roll.width}" × ${roll.length}" added`,
              timestamp: roll.created_at,
              material_type: roll.material_type
            });
          }
        });
      }

      // Sort by timestamp
      formattedActivities.sort((a, b) =>
        new Date(b.timestamp).getTime() - new Date(a.timestamp).getTime()
      );

      setActivities(formattedActivities.slice(0, 10));
    } catch (error) {
      console.error('Error fetching activities:', error);
    }
  };

  const markAsRead = async (notificationId: string) => {
    try {
      await notificationCrudService.markAsRead(notificationId);

      setNotifications(prev =>
        prev.map(n => n.id === notificationId ? { ...n, is_read: true } : n)
      );
      const newCount = Math.max(0, unreadCount - 1);
      setUnreadCount(newCount);

      // Emit event to update sidebar
      globalEvents.emit(EVENTS.NOTIFICATIONS_UPDATED, { unreadCount: newCount });

      toast.success('Notification marked as read');
    } catch (error) {
      console.error('Error marking as read:', error);
      toast.error('Failed to mark notification as read');
    }
  };

  const markAllAsRead = async () => {
    try {
      await notificationCrudService.markAllAsRead();

      setNotifications(prev => prev.map(n => ({ ...n, is_read: true })));
      setUnreadCount(0);

      // Emit event to update sidebar
      globalEvents.emit(EVENTS.NOTIFICATIONS_UPDATED, { unreadCount: 0 });

      toast.success('All notifications marked as read');
    } catch (error) {
      console.error('Error marking all as read:', error);
      toast.error('Failed to mark all as read');
    }
  };

  const openNotificationDetail = (notification: Notification) => {
    setSelectedNotification(notification);
    setDetailModalOpen(true);

    // Mark as read when opened
    if (!notification.is_read) {
      markAsRead(notification.id);
    }
  };

  const getActivityIcon = (type: string) => {
    switch (type) {
      case "cut":
        return <Package className="h-4 w-4" />;
      case "roll_added":
        return <CheckCircle className="h-4 w-4" />;
      case "roll_depleted":
        return <AlertTriangle className="h-4 w-4" />;
      default:
        return <Clock className="h-4 w-4" />;
    }
  };

  const getActivityColor = (type: string) => {
    switch (type) {
      case "cut":
        return "default";
      case "roll_added":
        return "secondary";
      case "roll_depleted":
        return "destructive";
      default:
        return "outline";
    }
  };

  const formatTimestamp = (timestamp: string) => {
    const date = new Date(timestamp);
    const now = new Date();
    const diff = now.getTime() - date.getTime();
    const hours = Math.floor(diff / (1000 * 60 * 60));
    const days = Math.floor(hours / 24);

    if (days > 0) return `${days} day${days > 1 ? 's' : ''} ago`;
    if (hours > 0) return `${hours} hour${hours > 1 ? 's' : ''} ago`;
    return 'Just now';
  };

  const getSeverity = (notification: Notification) => {
    if (notification.type !== 'low_stock') return 'default';
    const ratio = (notification.current_value || 0) / (notification.threshold_value || 1);
    return ratio < 0.5 ? 'high' : 'medium';
  };

  return (
    <div className="flex flex-col gap-4 md:gap-6">
      {/* Page Header */}
      <div className="flex flex-col gap-2 md:flex-row md:items-center md:justify-between">
        <div>
          <h1 className="text-2xl font-bold">
            Notifications
            {unreadCount > 0 && (
              <Badge variant="destructive" className="ml-2">
                {unreadCount} unread
              </Badge>
            )}
          </h1>
          <p className="text-muted-foreground">
            Stay updated on inventory alerts and recent activities
          </p>
        </div>
        <div className="flex gap-2">
          <Button
            variant="outline"
            onClick={markAllAsRead}
            disabled={unreadCount === 0}
          >
            Mark All as Read
          </Button>
          <Button
            onClick={async () => {
              try {
                await notificationCrudService.deleteAll();
                await fetchNotifications();
                toast.success('All notifications cleared');
              } catch (error) {
                console.error('Error clearing notifications:', error);
                toast.error('Failed to clear notifications');
              }
            }}
            variant="outline"
            size="sm"
            className="text-red-600 hover:text-red-700"
          >
            <Trash2 className="h-4 w-4 mr-2" />
            Clear All
          </Button>
        </div>
      </div>

      {/* Low Stock Alerts / Notifications */}
      <Card>
        <CardHeader>
          <CardTitle className="flex items-center gap-2">
            <AlertTriangle className="h-5 w-5 text-amber-600" />
            System Notifications
          </CardTitle>
          <CardDescription>
            Important alerts and notifications that need your attention
          </CardDescription>
        </CardHeader>
        <CardContent className="space-y-4">
          {loading ? (
            <div className="text-center py-8">Loading notifications...</div>
          ) : notifications.length > 0 ? (
            notifications.map((notification) => (
              <Alert
                key={notification.id}
                variant={getSeverity(notification) === "high" ? "destructive" : "default"}
                className={`cursor-pointer transition-opacity ${notification.is_read ? 'opacity-60' : ''}`}
                onClick={() => openNotificationDetail(notification)}
              >
                <AlertTriangle className="h-4 w-4" />
                <div className="flex flex-col gap-1 md:flex-row md:items-center md:justify-between w-full">
                  <div className="space-y-1 flex-1">
                    <AlertTitle className="flex items-center gap-2">
                      {notification.title}
                      {!notification.is_read && (
                        <Badge variant="destructive" className="text-xs">New</Badge>
                      )}
                    </AlertTitle>
                    <AlertDescription>
                      {notification.description}
                    </AlertDescription>
                    <p className="text-xs text-muted-foreground">
                      {formatTimestamp(notification.created_at)}
                    </p>
                  </div>
                  <div className="flex items-center gap-2">
                    {notification.type === 'low_stock' && (
                      <Badge variant={getSeverity(notification) === "high" ? "destructive" : "default"}>
                        {getSeverity(notification) === "high" ? "Critical" : "Low"}
                      </Badge>
                    )}
                    <Button
                      size="sm"
                      variant="ghost"
                      onClick={(e) => {
                        e.stopPropagation();
                        openNotificationDetail(notification);
                      }}
                    >
                      <Eye className="h-4 w-4" />
                    </Button>
                    {!notification.is_read && (
                      <Button
                        size="sm"
                        variant="ghost"
                        onClick={(e) => {
                          e.stopPropagation();
                          markAsRead(notification.id);
                        }}
                      >
                        <CheckCircle className="h-4 w-4" />
                      </Button>
                    )}
                  </div>
                </div>
              </Alert>
            ))
          ) : (
            <div className="text-center py-8 text-muted-foreground">
              <CheckCircle className="h-12 w-12 mx-auto mb-2 text-green-600" />
              <p>No notifications at this time!</p>
            </div>
          )}
        </CardContent>
      </Card>

      {/* Recent Activities */}
      <Card>
        <CardHeader>
          <CardTitle className="flex items-center gap-2">
            <Bell className="h-5 w-5" />
            Recent Activities
          </CardTitle>
          <CardDescription>
            Latest actions and events in the system
          </CardDescription>
        </CardHeader>
        <CardContent className="space-y-4">
          {activities.length > 0 ? (
            activities.map((activity) => (
              <div key={activity.id} className="flex items-start gap-3 p-3 rounded-lg border bg-card/50">
                <div className="flex-shrink-0">
                  <Badge variant={getActivityColor(activity.type) as any}>
                    {getActivityIcon(activity.type)}
                    {activity.type === 'cut' ? 'Cut' :
                     activity.type === 'roll_added' ? 'Added' : 'Depleted'}
                  </Badge>
                </div>
                <div className="flex-1 space-y-1">
                  <p className="text-sm font-medium">{activity.description}</p>
                  <div className="flex items-center gap-4 text-xs text-muted-foreground">
                    <span>{formatTimestamp(activity.timestamp)}</span>
                    {activity.job_reference && (
                      <span>Job: {activity.job_reference}</span>
                    )}
                    {activity.waste_percentage !== undefined && activity.waste_percentage !== null && (
                      <span className={activity.waste_percentage > 10 ? "text-amber-600" : ""}>
                        Waste: {activity.waste_percentage.toFixed(1)}%
                      </span>
                    )}
                  </div>
                </div>
              </div>
            ))
          ) : (
            <div className="text-center py-8 text-muted-foreground">
              <Clock className="h-12 w-12 mx-auto mb-2" />
              <p>No recent activities</p>
            </div>
          )}
        </CardContent>
      </Card>

      {/* Notification Detail Modal */}
      <Dialog open={detailModalOpen} onOpenChange={setDetailModalOpen}>
        <DialogContent className="sm:max-w-[500px]">
          <DialogHeader>
            <DialogTitle>{selectedNotification?.title}</DialogTitle>
            <DialogDescription>
              {formatTimestamp(selectedNotification?.created_at || '')}
            </DialogDescription>
          </DialogHeader>

          <div className="grid gap-4 py-4">
            <div>
              <Label>Description</Label>
              <p className="text-sm text-muted-foreground mt-1">
                {selectedNotification?.description}
              </p>
            </div>

            {selectedNotification?.type === 'low_stock' && (
              <>
                <div className="grid grid-cols-2 gap-4">
                  <div>
                    <Label>Current Stock</Label>
                    <p className="text-lg font-semibold">
                      {selectedNotification.current_value?.toFixed(1)} sqft
                    </p>
                  </div>
                  <div>
                    <Label>Minimum Threshold</Label>
                    <p className="text-lg font-semibold">
                      {selectedNotification.threshold_value?.toFixed(1)} sqft
                    </p>
                  </div>
                </div>

                <div>
                  <Label>Material Type</Label>
                  <p className="text-sm text-muted-foreground mt-1">
                    {selectedNotification.material_type}
                  </p>
                </div>

                <Alert>
                  <AlertTriangle className="h-4 w-4" />
                  <AlertTitle>Action Required</AlertTitle>
                  <AlertDescription>
                    Consider placing an order for {selectedNotification.material_type} to maintain adequate inventory levels.
                  </AlertDescription>
                </Alert>
              </>
            )}
          </div>

          <DialogFooter>
            <Button variant="outline" onClick={() => setDetailModalOpen(false)}>
              Close
            </Button>
            {selectedNotification?.type === 'low_stock' && (
              <Button onClick={() => {
                setDetailModalOpen(false);
                // Emit an event to open Quick Create with material pre-selected and suggested values
                const suggestedLength = 240; // Standard roll length
                const suggestedWidth = 36; // Standard width
                const deficit = (selectedNotification.threshold_value || 100) - (selectedNotification.current_value || 0);

                globalEvents.emit('OPEN_QUICK_CREATE', {
                  material_type: selectedNotification.material_type,
                  width: suggestedWidth.toString(),
                  length: suggestedLength.toString(),
                  thickness: '0.25', // Standard thickness
                  notes: `Low stock order - Current: ${selectedNotification.current_value?.toFixed(1)} sqft, Need: ${deficit.toFixed(1)} sqft minimum`
                });
                toast.success(`Opening Quick Create for ${selectedNotification.material_type} with suggested values`);
              }}>
                Order Material
              </Button>
            )}
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </div>
  );
}