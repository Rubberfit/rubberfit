// ─── Entity ────────────────────────────────────────────────────────────────

/**
 * A purchase order issued to a supplier. Carries its own line items
 * (`PurchaseOrderItem` value-object collection) and a 7-state lifecycle
 * machine from `value-objects/po-status.ts`.
 *
 * **Currency model.** The DB schema does not persist a currency column
 * on `purchase_orders` — money is stored as integer cents only. The
 * entity carries currency by piggy-backing on the `Money` VOs
 * (`subtotal`, `taxAmount`, `shippingCost`, `totalAmount` all share
 * one currency, and every item's `unitCost` / `lineTotal` must match).
 * The mapper layer is responsible for resolving the currency on read
 * (typically from the joined supplier or `tenant_settings.default_currency`)
 * and passing it through `currency` on `create` / `reconstitute`.
 *
 * **Money invariant.** `totalAmount === subtotal + taxAmount + shippingCost`,
 * where `subtotal` is the sum of all item `lineTotal`s. The aggregate
 * recomputes totals whenever items, tax, or shipping change.
 *
 * **Editable scope.** `updateDetails` and `replaceItems` only work in
 * `draft` or `pending_approval`. After approval the PO is locked except
 * for receipt recording and cancellation (and admin soft-delete).
 *
 * **Receipt flow.** `recordReceipt(lineNumber, qty, date, …)` validates
 * the line exists and that received quantity stays within ordered,
 * then auto-flips status to `partial_received` or `received` based on
 * aggregate fill. `actualDeliveryDate` is stamped when the PO becomes
 * fully received.
 *
 * Source: purchase_orders + purchase_order_items tables.
 */
