  // ─── Factories ───────────────────────────────────────────────────────────

  static create(props: CreatePurchaseOrderProps, now: Date = new Date()): PurchaseOrder {
    const poNumber = trimRequired(props.poNumber, "poNumber", PO_NUMBER_MAX, "PurchaseOrder")
    const paymentTerms = trimOptional(
      props.paymentTerms,
      "paymentTerms",
      PAYMENT_TERMS_MAX,
      "PurchaseOrder"
    )
    const notes = trimOptional(props.notes, "notes", null, "PurchaseOrder")

    const status: PoStatus = props.status ?? "draft"
    if (!isPoStatus(status)) {
      throw new InvalidEntityError("PurchaseOrder", `invalid status '${String(status)}'`)
    }

    PurchaseOrder.#assertDeliveryDates(props.orderDate ?? null, props.requestedDeliveryDate ?? null)

    const taxAmount = props.taxAmount ?? Money.zero(props.currency)
    const shippingCost = props.shippingCost ?? Money.zero(props.currency)
    PurchaseOrder.#assertMoneyNonNegative(taxAmount, "taxAmount")
    PurchaseOrder.#assertMoneyNonNegative(shippingCost, "shippingCost")
    PurchaseOrder.#assertSameCurrency([taxAmount, shippingCost], props.currency)

    const items = PurchaseOrder.#buildItems(props.items ?? [], props.currency)
    const subtotal = PurchaseOrder.#sumLineTotals(items, props.currency)
    const totalAmount = subtotal.add(taxAmount).add(shippingCost)

    return new PurchaseOrder({
      id: props.id,
      tenantId: props.tenantId,
      supplierId: props.supplierId,
      shippingAddressId: props.shippingAddressId ?? null,
      billingAddressId: props.billingAddressId ?? null,
      reorderRuleId: props.reorderRuleId ?? null,
      jobId: props.jobId ?? null,
      poNumber,
      status,
      orderDate: props.orderDate ?? null,
      requestedDeliveryDate: props.requestedDeliveryDate ?? null,
      actualDeliveryDate: props.actualDeliveryDate ?? null,
      subtotal,
      taxAmount,
      shippingCost,
      totalAmount,
      paymentTerms,
      notes,
      autoGenerated: props.autoGenerated ?? false,
      approvedBy: props.approvedBy ?? null,
      approvedAt: props.approvedAt ?? null,
      items,
      createdAt: now,
      createdBy: props.createdBy ?? null,
      updatedAt: now,
      updatedBy: null,
      deletedAt: null,
    })
  }

  static reconstitute(props: ReconstitutePurchaseOrderProps): PurchaseOrder {
    PurchaseOrder.#assertReconstituteInvariants(props)
    return new PurchaseOrder(props)
  }

