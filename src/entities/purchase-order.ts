import type { Money } from "./value-objects"
import type { AuditFields, SoftDeletable } from "./shared"
import type { Supplier } from "./supplier"
import type { PurchaseOrderItemWithDetails } from "./purchase-order-item"

export type CreatePurchaseOrder = Omit<
  PurchaseOrder,
  "id" | keyof AuditFields | keyof SoftDeletable
>
export type UpdatePurchaseOrder = Partial<CreatePurchaseOrder>

export interface PurchaseOrderWithDetails extends PurchaseOrder {
  supplier: Supplier
  items: PurchaseOrderItemWithDetails[]
}

export type PurchaseOrderStatus =
  | "draft"
  | "pending_approval"
  | "approved"
  | "ordered"
  | "partial_received"
  | "received"
  | "cancelled"

export interface PurchaseOrder extends AuditFields, SoftDeletable {
  id: string
  tenantId: string
  supplierId: string
  shippingAddressId: string | null
  billingAddressId: string | null
  reorderRuleId: string | null
  poNumber: string
  status: PurchaseOrderStatus
  orderDate: string | null
  requestedDeliveryDate: string | null
  actualDeliveryDate: string | null
  currency: string
  subtotal: Money
  taxAmount: Money
  shippingCost: Money
  totalAmount: Money
  paymentTerms: string | null
  notes: string | null
  autoGenerated: boolean
  approvedBy: string | null
  approvedAt: string | null
}
