import type { PurchaseOrder } from "@/src/entities/purchase-order"
import type { PoStatus } from "@/src/entities/value-objects/po-status"
import type {
  PurchaseOrder as LegacyPurchaseOrder,
  PurchaseOrderWithDetails,
  Supplier as LegacySupplier,
} from "@/src/infrastructure/models/supabase"

/**
 * Maps the new aggregate's `PoStatus` to the legacy row's narrower
 * status set. `pending_approval` → `pending` (legacy's name for the
 * same state) and `partial_received` → `received` (legacy has no
 * partial state, so we surface the more committed value to avoid
 * status-badge UI flicker).
 */
type LegacyPoStatus = LegacyPurchaseOrder["status"]
function mapStatus(status: PoStatus): LegacyPoStatus {
  if (status === "pending_approval") return "pending"
  if (status === "partial_received") return "received"
  return status
}

/**
 * Converts a `PurchaseOrder` entity to the legacy
 * `PurchaseOrderWithDetails` shape consumed by callers that haven't
 * migrated off the legacy row type yet (the cutting-engine + PO
 * surface pages).
 *
 * The bridge unwinds the entity's domain-typed values back to the
 * pre-redesign primitive form:
 *   • `Money` (cents) → `number` (dollars) for `subtotal`,
 *     `tax_amount`, `shipping_cost`, `total_amount`. Loss of precision
 *     is intentional — the legacy callers display these as floats.
 *   • `*Id` value objects → their primitive UUID string.
 *   • `Date` → ISO-8601 string (matches the Supabase row shape).
 *
 * The item collection is NOT projected here. None of the current
 * callers of the approve/reject/create/update use-cases read items
 * off the returned row (verified by grep). If a future caller does,
 * the right move is to migrate them to the entity directly, not to
 * grow this bridge with sqm→sqft inverse-conversions.
 */
export function purchaseOrderEntityToLegacy(
  po: PurchaseOrder,
  supplier?: { id: string; name: string } | null
): PurchaseOrderWithDetails {
  const row: LegacyPurchaseOrder = {
    id: po.id.value,
    user_id: po.createdBy?.value ?? "",
    po_number: po.poNumber,
    supplier_id: po.supplierId.value,
    status: mapStatus(po.status),
    order_date: po.orderDate?.toISOString() ?? undefined,
    requested_delivery_date: po.requestedDeliveryDate?.toISOString() ?? undefined,
    actual_delivery_date: po.actualDeliveryDate?.toISOString() ?? undefined,
    subtotal: po.subtotal.cents / 100,
    tax_amount: po.taxAmount.cents / 100,
    shipping_cost: po.shippingCost.cents / 100,
    total_amount: po.totalAmount.cents / 100,
    payment_terms: po.paymentTerms ?? undefined,
    shipping_address: undefined,
    billing_address: undefined,
    notes: po.notes ?? undefined,
    auto_generated: po.autoGenerated,
    approved_by: po.approvedBy?.value ?? undefined,
    approved_at: po.approvedAt?.toISOString() ?? undefined,
    reorder_rule_id: po.reorderRuleId?.value ?? undefined,
    job_id: po.jobId?.value ?? null,
    created_at: po.createdAt.toISOString(),
    updated_at: po.updatedAt.toISOString(),
  }

  const legacySupplier: LegacySupplier | undefined = supplier
    ? ({
        id: supplier.id,
        user_id: "",
        name: supplier.name,
        preferred: false,
        active: true,
        created_at: po.createdAt.toISOString(),
        updated_at: po.updatedAt.toISOString(),
      } as LegacySupplier)
    : undefined

  return {
    ...row,
    supplier: legacySupplier,
  }
}
