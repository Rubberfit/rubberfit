-- Create purchase_orders table
CREATE TABLE IF NOT EXISTS purchase_orders (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  po_number VARCHAR(50) NOT NULL UNIQUE,
  supplier_id UUID NOT NULL REFERENCES suppliers(id) ON DELETE RESTRICT,
  status VARCHAR(20) DEFAULT 'draft' CHECK (status IN ('draft', 'pending', 'approved', 'ordered', 'received', 'cancelled')),
  order_date DATE,
  requested_delivery_date DATE,
  actual_delivery_date DATE,
  subtotal DECIMAL(12,2) DEFAULT 0 CHECK (subtotal >= 0),
  tax_amount DECIMAL(12,2) DEFAULT 0 CHECK (tax_amount >= 0),
  shipping_cost DECIMAL(12,2) DEFAULT 0 CHECK (shipping_cost >= 0),
  total_amount DECIMAL(12,2) DEFAULT 0 CHECK (total_amount >= 0),
  payment_terms VARCHAR(100),
  shipping_address TEXT,
  billing_address TEXT,
  notes TEXT,
  created_by VARCHAR(100),
  approved_by VARCHAR(100),
  approved_at TIMESTAMPTZ,
  auto_generated BOOLEAN DEFAULT FALSE,
  reorder_rule_id UUID REFERENCES reorder_rules(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW(),

  -- Constraints
  CONSTRAINT valid_delivery_dates CHECK (
    requested_delivery_date IS NULL OR
    actual_delivery_date IS NULL OR
    actual_delivery_date >= order_date
  ),
  CONSTRAINT valid_approval CHECK (
    (status != 'approved' AND approved_by IS NULL AND approved_at IS NULL) OR
    (status = 'approved' AND approved_by IS NOT NULL AND approved_at IS NOT NULL)
  )
);

-- Create indexes
CREATE INDEX IF NOT EXISTS idx_purchase_orders_po_number ON purchase_orders(po_number);
CREATE INDEX IF NOT EXISTS idx_purchase_orders_supplier ON purchase_orders(supplier_id);
CREATE INDEX IF NOT EXISTS idx_purchase_orders_status ON purchase_orders(status);
CREATE INDEX IF NOT EXISTS idx_purchase_orders_order_date ON purchase_orders(order_date DESC);
CREATE INDEX IF NOT EXISTS idx_purchase_orders_delivery_date ON purchase_orders(requested_delivery_date);
CREATE INDEX IF NOT EXISTS idx_purchase_orders_auto_generated ON purchase_orders(auto_generated);
CREATE INDEX IF NOT EXISTS idx_purchase_orders_reorder_rule ON purchase_orders(reorder_rule_id);

-- Composite index for active PO queries
CREATE INDEX IF NOT EXISTS idx_purchase_orders_active
  ON purchase_orders(supplier_id, status, order_date DESC)
  WHERE status IN ('pending', 'approved', 'ordered');

