-- Create function to generate sequential PO numbers
CREATE OR REPLACE FUNCTION generate_po_number()
RETURNS TEXT AS $$
DECLARE
  year_suffix TEXT;
  next_sequence INTEGER;
  po_number TEXT;
BEGIN
  -- Get current year's last two digits
  year_suffix := TO_CHAR(CURRENT_DATE, 'YY');

  -- Get next sequence number for this year
  SELECT COALESCE(MAX(CAST(SUBSTRING(po_number FROM 'PO-' || year_suffix || '-(\d+)') AS INTEGER)), 0) + 1
  INTO next_sequence
  FROM purchase_orders
  WHERE po_number LIKE 'PO-' || year_suffix || '-%';

  -- Format: PO-YY-NNNN (e.g., PO-24-0001)
  po_number := 'PO-' || year_suffix || '-' || LPAD(next_sequence::TEXT, 4, '0');

  RETURN po_number;
END;
$$ LANGUAGE plpgsql;